from dataclasses import dataclass, field
from uuid import uuid4

from django.contrib.auth.models import User
from httpx import AsyncClient
from pydantic_ai.messages import BinaryContent


@dataclass
class Deps:
    agent_name: str
    current_user: User  # User that triggered the agent execution, used for permissions and context
    all_users: list[
        User
    ]  # All users in the conversation, used for context and permissions

    async def get_file(self, file_id: str) -> BinaryContent | None:
        """Fetch a file attached to the conversation by its ID, if supported."""
        return None


@dataclass
class MattermostDeps(Deps):
    channel_id: str
    channel_name: str
    mattermost_client: AsyncClient
    generated_files_ids: list[str] = field(
        default_factory=list
    )  # Files generated by the agent to include in the post

    async def upload_file(self, content: BinaryContent) -> str:
        response = await self.mattermost_client.post(
            "/files",
            content=content.data,
            params={
                "channel_id": self.channel_id,
                "filename": f"{uuid4().hex}.{content.format}",
            },
        )
        response.raise_for_status()

        file_id = response.json()["file_infos"][0]["id"]
        self.generated_files_ids.append(file_id)
        return file_id

    async def get_file(self, file_id: str) -> BinaryContent | None:
        r = await self.mattermost_client.get(f"/files/{file_id}")
        if r.status_code == 404:
            return None
        r.raise_for_status()

        if content_type := r.headers.get("Content-Type", None):
            content_type = content_type.split(";")[0]
        else:
            content_type = "application/octet-stream"

        return BinaryContent.narrow_type(
            BinaryContent(r.content, media_type=content_type)
        )


@dataclass
class ZulipDeps(Deps):
    channel_name: str  # Human readable description of where the conversation happens
    zulip_client: AsyncClient
    generated_files: list[tuple[str, str]] = field(
        default_factory=list
    )  # (name, upload path) of files generated by the agent, linked in the next message

    async def upload_file(
        self, content: BinaryContent, filename: str | None = None
    ) -> str:
        """Upload a file to Zulip and return its `/user_uploads/...` path."""
        if filename is None:
            filename = f"{uuid4().hex}.{content.format}"

        response = await self.zulip_client.post(
            "/user_uploads",
            files={"file": (filename, content.data, content.media_type)},
        )
        response.raise_for_status()

        data = response.json()
        path = data.get("url") or data["uri"]
        self.generated_files.append((filename, path))
        return path

    async def get_file(self, file_id: str) -> BinaryContent | None:
        if not file_id.startswith("/user_uploads/"):
            return None

        # Ask for a temporary URL that can be fetched without authentication
        r = await self.zulip_client.get(file_id.removeprefix("/"))
        if r.status_code == 404:
            return None
        r.raise_for_status()

        site = str(self.zulip_client.base_url).removesuffix("/").removesuffix("/api/v1")
        r = await self.zulip_client.get(
            site + r.json()["url"], follow_redirects=True
        )
        if r.status_code == 404:
            return None
        r.raise_for_status()

        if content_type := r.headers.get("Content-Type", None):
            content_type = content_type.split(";")[0]
        else:
            content_type = "application/octet-stream"

        return BinaryContent.narrow_type(
            BinaryContent(r.content, media_type=content_type)
        )

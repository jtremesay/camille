from dataclasses import dataclass, field
from uuid import uuid4

from django.contrib.auth.models import User
from httpx import AsyncClient
from pydantic_ai.messages import BinaryContent


@dataclass
class Deps:
    agent_name: str
    current_user: User  # User that triggered the agent execution, used for permissions and context
    all_users: list[
        User
    ]  # All users in the conversation, used for context and permissions

    async def get_file(self, file_id: str) -> BinaryContent | None:
        """Fetch a file attached to the conversation by its ID, if supported."""
        return None


@dataclass
class MattermostDeps(Deps):
    channel_id: str
    channel_name: str
    mattermost_client: AsyncClient
    generated_files_ids: list[str] = field(
        default_factory=list
    )  # Files generated by the agent to include in the post

    async def upload_file(self, content: BinaryContent) -> str:
        response = await self.mattermost_client.post(
            "/files",
            content=content.data,
            params={
                "channel_id": self.channel_id,
                "filename": f"{uuid4().hex}.{content.format}",
            },
        )
        response.raise_for_status()

        file_id = response.json()["file_infos"][0]["id"]
        self.generated_files_ids.append(file_id)
        return file_id

    async def get_file(self, file_id: str) -> BinaryContent | None:
        r = await self.mattermost_client.get(f"/files/{file_id}")
        if r.status_code == 404:
            return None
        r.raise_for_status()

        if content_type := r.headers.get("Content-Type", None):
            content_type = content_type.split(";")[0]
        else:
            content_type = "application/octet-stream"

        return BinaryContent.narrow_type(
            BinaryContent(r.content, media_type=content_type)
        )
